#!/usr/bin/env python3
"""Bump the release version everywhere it's declared, in one command.

The version lives in three places, and the 0.5.1 release showed what happens
when they're bumped by hand: pyproject.toml and uv.lock silently lagged (the
PEP-723 block and plugin.json moved first). This script is the one path
that's allowed to change the version:

1. plan the edits to pyproject.toml and .claude-plugin/plugin.json (the two
   hand-maintained declarations — uv.lock is derived, regenerated by `uv lock`,
   never hand-edited); both files are written only after both plans succeed,
   so a mid-way plan refusal never leaves a half-edited tree (a failed write
   is reported with restore instructions),
2. regenerate uv.lock so it reflects the new version and dependency pins,
3. re-run scripts/check_version_consistency.py as a self-check before exiting.

It refuses to run if pyproject.toml and plugin.json already disagree — that
state is drift to be fixed, not a starting point.

Usage: python3 scripts/bump_version.py 0.5.2
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+([-+][0-9A-Za-z.-]+)?$")
RESTORE = "git checkout pyproject.toml uv.lock .claude-plugin/plugin.json"


def _read_text(path: Path) -> str:
    try:
        return path.read_text()
    except FileNotFoundError:
        sys.exit(f"ERROR: {path} not found")
    except OSError as e:
        sys.exit(f"ERROR: {path}: {e}")
    except UnicodeDecodeError as e:
        sys.exit(f"ERROR: {path}: not UTF-8 text: {e}")


def _toml_version(path: Path, text: str) -> str:
    try:
        version = tomllib.loads(text)["project"]["version"]
    except (tomllib.TOMLDecodeError, KeyError, TypeError) as e:
        sys.exit(f"ERROR: {path}: cannot read [project].version: {e}")
    if not isinstance(version, str):
        sys.exit(f"ERROR: {path}: [project].version must be a string")
    return version


def _json_version(path: Path, text: str) -> str:
    try:
        version = json.loads(text)["version"]
    except (json.JSONDecodeError, KeyError, TypeError) as e:
        sys.exit(f'ERROR: {path}: cannot read "version": {e}')
    if not isinstance(version, str):
        sys.exit(f'ERROR: {path}: "version" must be a string')
    return version


def _plan_edit(path: Path, text: str, pattern: re.Pattern[str], new_version: str) -> str:
    """Return the rewritten file text, or exit if the version line isn't unique.

    Operates on the already-read `text`, so the version checked, the plan, and
    the write all share one snapshot. Matching is anchored to a full line
    (patterns carry re.M); a bare `version = "..."` string elsewhere in the
    file can't be hit, and the n != 1 refusal is the safety net for anything
    the anchor misses. The caller writes only after every plan succeeds, so a
    refusal here leaves the files untouched.
    """
    text, n = re.subn(
        pattern,
        lambda m: f"{m.group(1)}{new_version}{m.group(2)}",
        text,
    )
    if n != 1:
        sys.exit(f"ERROR: {path}: expected exactly one matching version line, found {n}")
    return text


def main() -> int:
    if len(sys.argv) != 2 or not VERSION_RE.match(sys.argv[1]):
        sys.exit("usage: python3 scripts/bump_version.py <new-version> (e.g. 0.5.2)")

    new_version = sys.argv[1]
    pyproject = ROOT / "pyproject.toml"
    plugin_json = ROOT / ".claude-plugin/plugin.json"
    check_script = ROOT / "scripts/check_version_consistency.py"

    pyproject_text = _read_text(pyproject)
    plugin_text = _read_text(plugin_json)
    old_version = _toml_version(pyproject, pyproject_text)
    plugin_version = _json_version(plugin_json, plugin_text)
    if old_version != plugin_version:
        sys.exit(
            f"ERROR: pyproject.toml ({old_version}) and plugin.json ({plugin_version}) "
            "disagree — run scripts/check_version_consistency.py and fix the drift first"
        )

    # `,?` in the plugin.json pattern echoes the original trailing comma, so the
    # output stays valid JSON whether "version" is the last key in the object
    # or a middle key followed by a comma.
    new_pyproject = _plan_edit(
        pyproject, pyproject_text, re.compile(r'^(version = ")[^"]+(")$', re.M), new_version
    )
    new_plugin = _plan_edit(
        plugin_json, plugin_text, re.compile(r'^(\s*"version": ")[^"]+(",?)$', re.M), new_version
    )
    try:
        try:
            pyproject.write_text(new_pyproject)  # both plans succeeded — commit both writes
            plugin_json.write_text(new_plugin)
        except OSError as e:
            sys.exit(
                f"ERROR: write failed: {e}; pyproject.toml and plugin.json may be half-edited. "
                f"Fix the file state, then restore and retry: {RESTORE} && "
                f"python3 scripts/bump_version.py {new_version}"
            )

        try:
            subprocess.run(["uv", "lock"], cwd=ROOT, check=True)
        except subprocess.CalledProcessError as e:
            sys.exit(
                f"ERROR: `uv lock` failed (exit {e.returncode}); pyproject.toml and plugin.json "
                f"are already edited. Fix the resolution error, then restore and retry: "
                f"{RESTORE} && python3 scripts/bump_version.py {new_version}"
            )
        except FileNotFoundError as e:
            # uv missing from PATH — or a wrapper script whose shebang interpreter
            # is gone (execve then fails with ENOENT, same as an absent binary).
            sys.exit(
                f"ERROR: could not run `uv lock`: {e}; uv is missing from PATH or its "
                "wrapper script's interpreter is missing — needed to regenerate uv.lock. "
                "pyproject.toml and plugin.json are already edited. Fix the issue, then "
                f"restore and retry: {RESTORE} && python3 scripts/bump_version.py {new_version}"
            )
        except OSError as e:
            # uv present but not runnable: ENOEXEC (corrupt binary, missing shebang)
            # and EACCES (missing +x bit, noexec mount) are both OSErrors, not
            # CalledProcessError; a wrapper whose shebang interpreter is gone raises
            # FileNotFoundError (ENOENT) and is handled by the branch above.
            sys.exit(
                f"ERROR: could not run `uv lock`: {e}; pyproject.toml and plugin.json are "
                f"already edited. Fix the issue, then restore and retry: "
                f"{RESTORE} && python3 scripts/bump_version.py {new_version}"
            )
    except KeyboardInterrupt:
        # A Ctrl-C mid-bump can leave pyproject/plugin.json bumped while uv.lock
        # still resolves the old version — say how to restore, then re-raise.
        sys.exit(
            f"ERROR: interrupted; pyproject.toml and plugin.json may be edited and uv.lock "
            f"stale. Restore and retry: {RESTORE} && python3 scripts/bump_version.py {new_version}"
        )

    if not check_script.exists():
        sys.exit(
            f"ERROR: {check_script} not found — can't self-check. Restore the edited "
            f"files with: {RESTORE}"
        )
    try:
        check = subprocess.run([sys.executable, str(check_script)], cwd=ROOT)
    except OSError as e:
        sys.exit(
            f"ERROR: could not run the self-check: {e}. Restore the edited files with: {RESTORE}"
        )
    if check.returncode != 0:
        sys.exit(
            "ERROR: post-bump consistency check failed (see output above); restore the "
            f"edited files with: {RESTORE}"
        )

    print(f"Bumped {old_version} -> {new_version}: pyproject.toml, plugin.json, uv.lock.")
    print(f'Commit suggestion:  git add -u && git commit -m "release: bump to {new_version}"')
    return 0


if __name__ == "__main__":
    sys.exit(main())
